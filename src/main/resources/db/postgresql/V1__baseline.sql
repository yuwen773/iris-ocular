-- ============================================================================
-- Iris · PostgreSQL 18 baseline (Flyway V1 for the PostgreSQL line)
--
-- Generated from the live MySQL line's final schema (Flyway V1..V47 applied to a
-- throwaway MySQL 8.0.46 instance), then reviewed by hand. See
-- docs/architecture/postgresql-pgvector-migration-report-2026-11-28.md.
--
-- Conventions
--   * identifiers are unquoted and lowercase; MyBatis-Plus emits camelCase
--     identifiers unquoted, which PostgreSQL folds to the same lowercase name;
--   * DATETIME/TIMESTAMP -> timestamptz(p): the database stores instants, the
--     JDBC session runs in UTC, and API values keep their explicit offset;
--   * AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY (explicit-id imports do
--     not consume the sequence; the migration tool re-syncs it afterwards);
--   * ON UPDATE CURRENT_TIMESTAMP -> BEFORE UPDATE trigger (iris_touch_column).
-- ============================================================================
CREATE EXTENSION IF NOT EXISTS vector;

-- MySQL's ON UPDATE CURRENT_TIMESTAMP equivalent. The trigger overwrites the
-- column on every UPDATE; MySQL skipped the touch when no value changed, so the
-- only observable difference is a bumped timestamp on a no-op UPDATE.
-- PL/pgSQL cannot assign a dynamically named NEW field directly; the row is
-- round-tripped through jsonb, which preserves every column type (numeric,
-- bytea, arrays) and lets the trigger stay column-generic.
CREATE OR REPLACE FUNCTION iris_touch_column() RETURNS trigger AS $$
BEGIN
    NEW := jsonb_populate_record(
        NEW,
        jsonb_set(to_jsonb(NEW), ARRAY[TG_ARGV[0]], to_jsonb(now()))
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

